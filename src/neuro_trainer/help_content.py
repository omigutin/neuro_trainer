from __future__ import annotations

"""
    HelpContent — структурированная «человеческая» справка по обучению YOLO (CLS/DET/SEG).
    Эта строка предназначена для показа в окне Help (GUI) или в Markdown/HTML-виджете.
    
    Формат выдачи:
    - get_markdown(): возвращает длинный Markdown-текст.
    - get_sections(): отдаёт словарь {раздел: текст} — удобно, если хочешь рендерить частями.
    
    Ссылки на документацию Ultralytics (для удобства скопировать в браузер):
    - Главная:           https://docs.ultralytics.com
    - Классификация:     https://docs.ultralytics.com/tasks/classify/
    - Детекция:          https://docs.ultralytics.com/tasks/detect/
    - Сегментация:       https://docs.ultralytics.com/tasks/segment/
    - Параметры train(): https://docs.ultralytics.com/modes/train/
    - Валидация:         https://docs.ultralytics.com/modes/val/
"""

from textwrap import dedent


class HelpContent:
    @staticmethod
    def get_sections() -> dict[str, str]:
        md_intro = dedent("""
        # Коротко: как выбирать настройки

        **Шаги:**
        1. Выбери модель (из списка YOLO или локальный `.pt`). Тип задачи подставится автоматически.
        2. Выбери профиль: **fast** (быстро проверить), **quality** (выжать качество), **low_vram** (не падать по памяти).
        3. Проверь **data** и **project_dir**. Если `name` пустой — мы создадим `runN`.
        4. Нажми **Валидация** — быстрый чек путей/датасета/метрик.
        5. Нажми **Старт** — пойдёт обучение. Итоговые метрики лежат в `final_metrics.json` и `final_metrics_extra.csv`.

        **Памятка по `imgsz`:**
        - Классификация: одно число (квадрат). 224 — быстро, 320 — баланс, 384 — качество.
        - Детекция/Сегментация: одно число или `HxW`. Мы автоматически округлим каждую сторону до кратности 32.
        """)

        md_cls = dedent("""
        # Классификация (Classifier)

        ## Когда выбирать
        Когда задача — отнести картинку целиком к одному из классов.
        Примеры: «пустой лоток / лоток полный / коробка / фон».

        ## Ключевые параметры
        - `imgsz` (int): итоговый квадратный размер входа. Больше — лучше видит мелкие детали, но медленнее.
          * 224 → очень быстро
          * 320 → баланс скорости/качества
          * 384 → качество (если хватает VRAM)
        - `batch`: сколько изображений за раз. Больше — быстрее на мощном GPU, но требует память.
        - `epochs`: сколько «кругов» обучения. Для качества 60–120 — типично.
        - `patience`: если качество (top1/top5) не растёт N эпох — остановимся раньше.

        ## Полезные «мешалки» (аугментации/регуляризация)
        - `auto_augment="randaugment"` — «умная мешалка» картинок; помогает не заучивать.
        - `erasing` (0..1) — случайно затираем кусок картинки → лучше устойчивость.
        - `label_smoothing` (0..1) — слегка «размываем» метку → меньше переобучение.
        - `dropout` (0..1) — иногда выключаем часть нейронов при обучении.

        ## Как читать метрики
        - `top1` — доля правильных ответов с первой попытки. Это основной ориентир.
        - `top5` — для 3–5 классов почти всегда близок к 1.0, поэтому смотрим именно на `top1`.

        ## Типичные ситуации
        - «Мелкие различия, модель путается»: увеличь `imgsz` (например, 224 → 320/384).
        - «Падает по памяти»: уменьши `batch`, затем `imgsz`, или выбери профиль `low_vram`.
        - «Быстро проверить идею»: профиль `fast` (меньше эпох + стандартные аугментации).
        """)

        md_det = dedent("""
        # Детекция (Detector)

        ## Когда выбирать
        Когда нужно найти **объекты и их коробки** на изображении.

        ## Ключевые параметры
        - `imgsz` (int или HxW): 640 — «классика», 800 — детальнее (медленнее), 512 — экономия VRAM.
        - `rect=True` — батчи с похожими пропорциями; меньше паддинга и искажений.
        - `multi_scale=True` — меняем масштаб на лету; даёт устойчивость к расстоянию до объектов.
        - `batch`, `epochs`, `patience` — как в классификации, но учти, что детектор учится дольше.

        ## Как читать метрики
        - `mAP50-95` — средняя точность по IoU 0.50..0.95 (чем выше, тем лучше).
        - `mAP50` — порог IoU 0.50 (оптимистичнее, иногда полезно для ранней оценки).

        ## Типичные ситуации
        - «Объекты очень мелкие»: увеличь `imgsz` (например, 640 → 800), включи `multi_scale`.
        - «Сцены разной ориентации (верт/гориз)»: `rect=True` уменьшит паддинг.
        - «OOM (Out of Memory)»: уменьшай `batch`, дальше — `imgsz`, или выбери профиль `low_vram`.
        """)

        md_seg = dedent("""
        # Сегментация (Segmentator)

        ## Когда выбирать
        Когда нужно выделить **точную форму** объектов (пиксельные маски), а не просто коробку.

        ## Ключевые параметры
        - `imgsz` (int или HxW): требования к памяти выше, чем у детекции.
        - `rect=True`, `multi_scale=True` — по смыслу почти как у детекции, обычно дают плюс к обобщению.
        - `batch` — сохраняй осторожность: для сегментации он часто меньше при том же GPU.

        ## Метрики
        Зачастую те же, что у детекции (mAP по маскам); в Ultralytics API они лежат рядом с `box`.

        ## Типичные ситуации
        - «Пишет, что не хватает памяти» — первым делом уменьши `batch`; при необходимости — `imgsz`.
        - «Хочется точнее границы» — рост `imgsz` и более качественные данные дают наибольший эффект.
        """)

        md_links = dedent("""
        # Полезные ссылки
        - Документация Ultralytics: https://docs.ultralytics.com
        - Классификация:           https://docs.ultralytics.com/tasks/classify/
        - Детекция:                https://docs.ultralytics.com/tasks/detect/
        - Сегментация:             https://docs.ultralytics.com/tasks/segment/
        - Параметры train():       https://docs.ultralytics.com/modes/train/
        - Валидация:               https://docs.ultralytics.com/modes/val/
        """)

        return {
            "intro": md_intro,
            "classifier": md_cls,
            "detector": md_det,
            "segmentator": md_seg,
            "links": md_links,
        }

    @staticmethod
    def get_markdown() -> str:
        """Склеивает все разделы в один большой Markdown-текст."""
        s = HelpContent.get_sections()
        return "\n\n".join([s["intro"], s["classifier"], s["detector"], s["segmentator"], s["links"]])
